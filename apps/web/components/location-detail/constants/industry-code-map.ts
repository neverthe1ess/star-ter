/**
 * 서울시 API 코드를 DB 쿼리용 코드로 변환
 * @param seoulCode 서울시 API 코드 (예: 'CS100007')
 * @returns DB 쿼리용 코드 (예: 'I21006') 또는 코드 배열
 */
export function convertSeoulCodeToDbCode(
  seoulCode: string,
): string | string[] | null {
  return SEOUL_TO_DB_CODE_MAP[seoulCode] || null;
}

